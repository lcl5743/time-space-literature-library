import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
// Read-only review queue for the canonical snapshot. It never edits data/; corrections need source evidence and a PROVENANCE update.
const json=async name=>JSON.parse(await readFile(path.join(root,'data',name),'utf8'));
const library=await json('library.json'),citations=await json('citations.json'),papers=library.papers,records=citations.records;
const norm=t=>String(t||'').toLowerCase().replace(/^\s*(?:论文[:：]\s*)?\d{4}\s*\[arxiv\]\s*|^\s*arxiv[:：]\s*/i,'').replace(/[^a-z0-9]/g,'');
function dice(a,b){if(!a||!b)return 0;if(a===b)return 1;const grams=s=>{const m=new Map();for(let i=0;i<s.length-1;i++){const g=s.slice(i,i+2);m.set(g,(m.get(g)||0)+1)}return m},x=grams(a),y=grams(b);let hit=0;for(const [g,c] of x)hit+=Math.min(c,y.get(g)||0);return 2*hit/Math.max(1,a.length+b.length-2)}
const cell=v=>String(v??'—').replace(/\|/g,'\\|').replace(/\s+/g,' ').trim()||'—';
const row=p=>`| ${p.id} | ${cell(p.year)} | ${cell(p.venue)} | ${cell(p.title.slice(0,110))} | ${cell(records[p.id]?.status)} |`;
const head='| ID | Year | Venue | Title | Citation |\n| --- | --- | --- | --- | --- |';
function collisions(field,clean){
 const groups=new Map();for(const p of papers){const key=clean(p[field]);if(key){if(!groups.has(key))groups.set(key,[]);groups.get(key).push(p)}}
 return [...groups].filter(([,ps])=>ps.length>1).map(([key,ps])=>{const t=ps.map(p=>norm(p.title));let low=1;for(let i=0;i<t.length;i++)for(let j=i+1;j<t.length;j++)low=Math.min(low,t[i].includes(t[j])||t[j].includes(t[i])?1:dice(t[i],t[j]));return {field,key,papers:ps,kind:low>=0.6?'likely duplicate record':'conflicting identifier'}}).sort((a,b)=>a.kind.localeCompare(b.kind)||a.key.localeCompare(b.key));
}
const shared=[...collisions('doi',x=>String(x||'').trim().toLowerCase()),...collisions('arxiv',x=>String(x||'').trim().replace(/v\d+$/,''))];
const duplicates=shared.filter(x=>x.kind==='likely duplicate record'),conflicts=shared.filter(x=>x.kind==='conflicting identifier');
const noYear=papers.filter(p=>!p.year),noVenue=papers.filter(p=>!p.venue);
const yearGaps=papers.filter(p=>records[p.id]?.status==='matched'&&p.year&&records[p.id].source_publication_year&&Math.abs(p.year-records[p.id].source_publication_year)>1);
const group=x=>`#### ${x.field.toUpperCase()} \`${x.key}\`\n\n${head}\n${x.papers.map(row).join('\n')}\n`;
const report=`# Data audit — snapshot ${library.date}

Generated by \`npm run audit -- --write\` from \`data/library.json\` and \`data/citations.json\`. This is a review queue, not a correction: no record was changed. Fix a record only with source evidence, keep stable IDs (use \`id_aliases\` when merging), and update \`data/PROVENANCE.json\`.

## Summary

| Check | Count |
| --- | ---: |
| Records | ${papers.length} |
| DOI/arXiv shared by records with similar titles (likely duplicates or versions) | ${duplicates.length} groups |
| DOI/arXiv shared by records with dissimilar titles (identifier or version relationship to review) | ${conflicts.length} groups |
| Records without a year | ${noYear.length} |
| Records without a venue | ${noVenue.length} |
| Matched citations whose OpenAlex year differs from the library year by more than one | ${yearGaps.length} |

Title similarity uses character bigrams over normalized titles (threshold 0.6, or one title containing the other). These are group-level triage labels, not verified identity decisions. A mixed group may contain both duplicate candidates and a different work; inspect each pair against source metadata. Different titles alone do not prove an identifier is wrong, and similar titles do not establish that records should be merged. Preprints, renamed papers and substantive journal extensions need explicit version checks.

## Shared identifiers with title disagreement

Citation match status is separate from identifier correctness: a title-based match can coexist with a wrong DOI or arXiv field. Review the official identifier landing page, authors and version history before changing either the record or citation mapping. Unverified identifiers can still appear in detail pages, RIS and CSV exports.

${conflicts.map(group).join('\n')||'None.\n'}
## Likely duplicate records

Possible preprint/proceedings versions, title changes or blog-list prefixes. Check official titles, authors and version history before merging through \`id_aliases\`. Keep substantive journal extensions as separate related records. Counts are identifier groups, not distinct works or a number of records to delete; one pair can appear in both DOI and arXiv queues.

${duplicates.map(group).join('\n')||'None.\n'}
## Citation year differences

These rows only establish a year difference greater than one. Possible explanations include preprint/proceedings dates, publisher or aggregator metadata, a wrong library year, or a mismatched work. This script does not establish which source is wrong. Verify the title, authors, publication type, official proceedings year and version history per record before correcting a year or citation join. A confirmed library-year correction changes the year ranking.

| ID | Library year | OpenAlex year | Venue | Title | Match |
| --- | --- | --- | --- | --- | --- |
${yearGaps.map(p=>`| ${p.id} | ${p.year} | ${records[p.id].source_publication_year} | ${cell(p.venue)} | ${cell(p.title.slice(0,90))} | ${records[p.id].match_method} |`).join('\n')}

## Missing year or venue

These records form the "Unknown" group in the year and venue rankings.

<details><summary>${noYear.length} without year</summary>

${head}
${noYear.map(row).join('\n')}

</details>

<details><summary>${noVenue.length} without venue</summary>

${head}
${noVenue.map(row).join('\n')}

</details>
`;
if(process.argv.includes('--write')){const file=path.join(root,'docs/review/data-audit.md');await mkdir(path.dirname(file),{recursive:true});await writeFile(file,report);console.log(`Wrote ${path.relative(root,file)}: ${conflicts.length} title-disagreement groups, ${duplicates.length} likely duplicate groups, ${noYear.length} without year, ${noVenue.length} without venue, ${yearGaps.length} citation year gaps`)}
else process.stdout.write(report);
